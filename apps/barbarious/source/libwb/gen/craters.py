#!/usr/bin/env python3
"""Generate wb_craters.h: the craters on the home screen's moon.

The canvas "Menu's met frontpaneel" (claude.ai, 2026-10-27, the scene with
"moonPattern") gives the moon craters: holes in its disc, in the void's
colour, anti-aliased. moon-craters.png keeps them as a mask (white: all
crater) in panel pixels at rotation 0, from the top left corner; this turns
it into runs of 4-bit coverage for home.c, which draws them turned with the
moon (scene_craters()).

    python3 craters.py --from design.png   # the canvas's scene -> moon-craters.png
    python3 craters.py > ../wb_craters.h

--from takes the 720 x 720 scene picture: inside the moon's disc (from
../wb_scene_data.h, 2.5 px in from its edge) a pixel's crater coverage is how
far it is from the disc's tone (35, 35, 49) towards the void (10, 10, 20).
Needs python3-pil. The output is checked in.
"""
import argparse
import os
import re

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
MASK = os.path.join(HERE, "moon-craters.png")
DISC, VOID = 35, 10      # the red channel of the disc and the void


def moon():
    s = open(os.path.join(HERE, "..", "wb_scene_data.h")).read()
    m = re.search(r"scene_moon\[4\] = \{([^}]*)\}", s)
    cx, cy, r, _ = (int(v) / 16 for v in m.group(1).split(","))
    return cx, cy, r


def extract(path):
    im = Image.open(path).convert("RGB")
    cx, cy, r = moon()
    w, h = int(cx + r) + 1, int(cy + r) + 1
    out = Image.new("L", (min(w, im.width), min(h, im.height)))
    for y in range(out.height):
        for x in range(out.width):
            if ((x + 0.5 - cx) ** 2 + (y + 0.5 - cy) ** 2) ** 0.5 >= r - 2.5:
                continue
            a = (DISC - im.getpixel((x, y))[0]) * 255 // (DISC - VOID)
            out.putpixel((x, y), max(0, min(255, a)) if a >= 12 else 0)
    box = out.getbbox()
    out.crop((0, 0, box[2], box[3])).save(MASK, optimize=True)


def header():
    m = Image.open(MASK).convert("L")
    data, runs = [], 0
    for y in range(m.height):
        x = 0
        while x < m.width:
            if not m.getpixel((x, y)) >> 4:
                x += 1
                continue
            n = 0
            while x + n < m.width and n < 255 and m.getpixel((x + n, y)) >> 4:
                n += 1
            nib = [m.getpixel((x + i, y)) >> 4 for i in range(n)] + [0]
            data += [y >> 8, y & 255, x >> 8, x & 255, n]
            data += [nib[i] << 4 | nib[i + 1] for i in range(0, n, 2)]
            runs += 1
            x += n
    lines = ["/* Generated by libwb/gen/craters.py from moon-craters.png. */",
             "/*",
             " * The moon's craters (the canvas \"Menu's met frontpaneel\", 2026-10-27),",
             " * in panel pixels at rotation 0: runs of y (2 bytes), x (2), n, then n",
             " * coverages of 4 bits, two to a byte (the first in the high half).",
             " */",
             "#pragma once",
             "#define SCENE_CRATER_RUNS %d" % runs,
             "static const uint8_t scene_craters[%d] = {" % len(data)]
    for i in range(0, len(data), 16):
        lines.append("\t" + ", ".join("%d" % b for b in data[i:i + 16]) + ",")
    lines.append("};")
    print("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--from", dest="src")
    a = ap.parse_args()
    if a.src:
        extract(a.src)
    else:
        header()


if __name__ == "__main__":
    main()
